import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean; activeGlow?: boolean }
>(({ className, hoverEffect = false, activeGlow = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-border bg-surface text-foreground shadow-md transition-all duration-200",
      hoverEffect && "hover:border-primary/50 hover:bg-surface-elevated hover:shadow-xl hover:shadow-black/40",
      activeGlow && "border-primary shadow-lg shadow-primary/20",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

